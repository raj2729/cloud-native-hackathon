'use client';

/**
 * Dash0 website monitoring: page views, Web Vitals, fetch/XHR spans, errors and
 * rage clicks come from the SDK. On top of that we record how the page is being
 * used — never who is using it:
 *
 * - `app.a11y.input_mode` (keyboard / pointer / touch), mirrored into the
 *   `a11y_input` cookie so server actions can tag their spans and metrics with
 *   it (see `lib/input-mode.ts`). This is what the keyboard-fairness SLO is
 *   built on.
 * - Browser accessibility preferences: reduced motion, forced colours, higher
 *   contrast, enlarged default text, and an approximate zoom bucket.
 * - `a11y.focus_trap` events when repeated Tab presses fail to move focus.
 *
 * Renders nothing, and does nothing at all without the NEXT_PUBLIC_DASH0_* vars.
 */
import { useEffect } from 'react';

type InputMode = 'keyboard' | 'pointer' | 'touch';

const COOKIE = 'a11y_input';
const FOCUS_TRAP_TABS = 5;
const NAV_KEYS = new Set(['Tab', 'ArrowUp', 'ArrowDown', 'ArrowLeft', 'ArrowRight']);

function media(query: string): boolean {
  try {
    return window.matchMedia(query).matches;
  } catch {
    return false;
  }
}

/** Coarse page zoom on desktop browsers. Buckets only, so it cannot fingerprint anyone. */
function zoomBucket(): string {
  const ratio = window.outerWidth > 0 && window.innerWidth > 0 ? window.outerWidth / window.innerWidth : 1;
  if (ratio < 1.15) return '100';
  if (ratio < 1.8) return '125-175';
  return '200+';
}

/** True when the visitor has raised the browser's default text size above 16px. */
function enlargedText(): boolean {
  try {
    return Number.parseFloat(getComputedStyle(document.documentElement).fontSize) > 16;
  } catch {
    return false;
  }
}

function preferenceAttributes(): Record<string, string | boolean> {
  return {
    'app.a11y.reduced_motion': media('(prefers-reduced-motion: reduce)'),
    'app.a11y.forced_colors': media('(forced-colors: active)'),
    'app.a11y.prefers_contrast': media('(prefers-contrast: more)'),
    'app.a11y.enlarged_text': enlargedText(),
    'app.a11y.zoom_bucket': zoomBucket(),
  };
}

function readCookieMode(): InputMode | null {
  const match = document.cookie.match(/(?:^|;\s*)a11y_input=(keyboard|pointer|touch)/);
  return match ? (match[1] as InputMode) : null;
}

function writeCookieMode(mode: InputMode): void {
  document.cookie = `${COOKIE}=${mode}; path=/; max-age=${60 * 60 * 24}; samesite=lax`;
}

/** Element description for a focus-trap event: tag, role and id only — no text content. */
function describe(el: Element | null): string {
  if (!el) return 'none';
  const role = el.getAttribute('role');
  return `${el.tagName.toLowerCase()}${role ? `[role=${role}]` : ''}${el.id ? `#${el.id}` : ''}`;
}

export function Dash0Rum(): null {
  useEffect(() => {
    const url = process.env.NEXT_PUBLIC_DASH0_ENDPOINT;
    const authToken = process.env.NEXT_PUBLIC_DASH0_AUTH_TOKEN;
    if (!url || !authToken) return;

    let disposed = false;
    const cleanups: (() => void)[] = [];

    void (async () => {
      // Imported lazily so the SDK never runs during server rendering.
      const sdk = await import('@dash0/sdk-web');
      if (disposed) return;

      let mode: InputMode = readCookieMode() ?? 'pointer';
      writeCookieMode(mode);

      sdk.init({
        serviceName: 'confluence-web',
        serviceNamespace: 'confluence',
        environment: process.env.NEXT_PUBLIC_DEPLOYMENT_ENV ?? 'hackathon',
        endpoint: { url, authToken, dataset: process.env.NEXT_PUBLIC_DASH0_DATASET ?? 'default' },
        additionalSignalAttributes: {
          'app.a11y.input_mode': mode,
          ...preferenceAttributes(),
          // Traffic generated by our own simulator is labelled so it can be filtered out.
          'app.traffic.synthetic': new URLSearchParams(window.location.search).has('synthetic'),
        },
      });

      const setMode = (next: InputMode): void => {
        if (next === mode) return;
        const previous = mode;
        mode = next;
        writeCookieMode(next);
        sdk.addSignalAttribute('app.a11y.input_mode', next);
        sdk.sendEvent('a11y.input_mode_changed', {
          title: `Input mode changed to ${next}`,
          attributes: { 'app.a11y.input_mode.previous': previous, 'app.a11y.input_mode': next },
        });
      };

      // Focus-trap detection: N Tab presses in a row that leave focus where it was.
      let stuckTabs = 0;
      const onKeyDown = (event: KeyboardEvent): void => {
        if (!NAV_KEYS.has(event.key)) return;
        setMode('keyboard');
        if (event.key !== 'Tab') return;

        const before = document.activeElement;
        window.setTimeout(() => {
          if (document.activeElement === before) stuckTabs += 1;
          else stuckTabs = 0;
          if (stuckTabs >= FOCUS_TRAP_TABS) {
            stuckTabs = 0;
            sdk.sendEvent('a11y.focus_trap', {
              title: 'Keyboard focus did not move after repeated Tab presses',
              severity: 'WARN',
              attributes: {
                'app.a11y.element': describe(before),
                'app.page.path': window.location.pathname,
              },
            });
          }
        }, 0);
      };

      const onPointerDown = (event: PointerEvent): void => {
        setMode(event.pointerType === 'touch' ? 'touch' : 'pointer');
      };

      // Preferences can change mid-session (e.g. the visitor zooms in).
      const onResize = (): void => {
        sdk.addSignalAttribute('app.a11y.zoom_bucket', zoomBucket());
      };

      window.addEventListener('keydown', onKeyDown, true);
      window.addEventListener('pointerdown', onPointerDown, true);
      window.addEventListener('resize', onResize);
      cleanups.push(() => {
        window.removeEventListener('keydown', onKeyDown, true);
        window.removeEventListener('pointerdown', onPointerDown, true);
        window.removeEventListener('resize', onResize);
      });
    })().catch(() => {
      // Monitoring must never break the page.
    });

    return () => {
      disposed = true;
      for (const cleanup of cleanups) cleanup();
    };
  }, []);

  return null;
}
